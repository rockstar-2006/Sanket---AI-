#!/usr/bin/env bash
# Sanket AI — Indian Sign Language (ISL) Dataset CLI Installer (Mac / Linux Bash)
# Usage: curl -fsSL https://sanket.ai/get-dataset.sh | bash

set -e

echo ""
echo -e "\033[1;33m==================================================================\033[0m"
echo -e "\033[1;32m   SANKET AI — Authentic Indian Sign Language (ISL) Dataset CLI\033[0m"
echo -e "\033[0;37m   288 Vocabulary Words • 262 Parquet Motion Captures • 30 FPS\033[0m"
echo -e "\033[1;33m==================================================================\033[0m"
echo ""

TARGET_DIR="./sanket-isl-dataset"
mkdir -p "$TARGET_DIR"

METADATA_URL="https://sanket-ai.onrender.com/api/dataset/download"
FALLBACK_URL="http://localhost:3000/api/dataset/download"

echo -e "\033[0;36m[-] Connecting to Sanket AI Dataset Repository...\033[0m"

if command -v curl >/dev/null 2>&1; then
    curl -fsSL "$METADATA_URL" -o "$TARGET_DIR/dataset_catalog.json" 2>/dev/null || \
    curl -fsSL "$FALLBACK_URL" -o "$TARGET_DIR/dataset_catalog.json" 2>/dev/null || true
elif command -v wget >/dev/null 2>&1; then
    wget -q "$METADATA_URL" -O "$TARGET_DIR/dataset_catalog.json" 2>/dev/null || \
    wget -q "$FALLBACK_URL" -O "$TARGET_DIR/dataset_catalog.json" 2>/dev/null || true
fi

cat << 'EOF' > "$TARGET_DIR/README.md"
# Sanket AI — Indian Sign Language (ISL) Dataset

## Dataset Specifications
- **Total Vocabulary**: 288 Accessible Gestures
- **Ground-Truth Motion Recordings**: 262 Apache Parquet Files (.parquet)
- **Fingerspelling Letters**: 26 Static & Dynamic Letters (A-Z)
- **Kinematic Landmark Nodes**: 21 3D Points per hand (42 Dual-Hand Points: x, y, z)
- **Sampling Frequency**: 30 FPS Real-time Web Worker Motion Pipeline
- **Coordinate Space**: Normalized [0.0 - 1.0] Camera Viewport Space

## Quickstart (Python & Pandas)
```python
import pandas as pd

# Load any gesture recording
df = pd.read_parquet("doctor_MVI_0128.parquet")
print("Columns:", df.columns)
print(df.head())
```

## Quickstart (PyTorch / TensorFlow)
```python
